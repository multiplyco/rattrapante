(ns generate-bindings
  "Generate exact Java downcalls from the pinned Rust C-ABI declarations.
  This parser is intentionally limited to that API and rejects unknown ABI types."
  (:require [babashka.fs :as fs]
    [clojure.string :as str]))


(defn abi
  "Return [Java type, FFM layout] for a supported Rust C-ABI type."
  [rust-type]
  (let [t (str/trim rust-type)]
    (cond
      (or (str/starts-with? t "*const ") (str/starts-with? t "*mut "))
      ["MemorySegment" "ValueLayout.ADDRESS"]

      (str/starts-with? t "AMitems") ["MemorySegment" "FFM.ITEMS"]
      (= t "AMbyteSpan") ["MemorySegment" "FFM.SPAN"]
      (#{"usize" "isize" "u64" "i64"} t) ["long" "ValueLayout.JAVA_LONG"]
      (#{"AMstatus" "AMvalType" "AMidxType" "AMobjType" "AMmarkExpand" "c_int"} t)
      ["int" "ValueLayout.JAVA_INT"]

      (= t "bool") ["boolean" "ValueLayout.JAVA_BOOLEAN"]
      (= t "f64") ["double" "ValueLayout.JAVA_DOUBLE"]
      (empty? t) ["void" nil]
      :else (throw (ex-info "Unrecognized ABI type" {:rust-type t})))))


(defn parse-argument
  [argument]
  (let [[name rust-type] (str/split argument #":" 2)
        [java-type layout] (abi rust-type)]
    {:name (str/trim name) :java-type java-type :layout layout}))


(def declaration-pattern
  #"(?s)pub (?:unsafe )?extern \"C\" fn (AM\w+)(?:<[^>]+>)?\((.*?)\)\s*(?:->\s*([^{]+))?\s*\{")


(defn exported-functions
  [path]
  (mapv
    (fn [[_ name arguments return-type]]
      {:name name
       :arguments (into [] (comp (remove str/blank?) (map parse-argument))
                    (str/split arguments #","))
       :return (abi (or return-type ""))})
    (re-seq declaration-pattern (slurp (fs/file path)))))


(defn render-function
  [{:keys [name arguments] [return-type return-layout] :return}]
  (let [layouts (cond->> (map :layout arguments)
                  return-layout (cons return-layout))
        descriptor (str (if return-layout "FunctionDescriptor.of" "FunctionDescriptor.ofVoid")
                     "(" (str/join ", " layouts) ")")
        ;; FFM adds a leading allocator argument for a struct returned by value.
        java-arguments (if (#{"FFM.SPAN" "FFM.ITEMS"} return-layout)
                         (into [{:name "allocator" :java-type "SegmentAllocator"}] arguments)
                         arguments)
        signature (str/join ", " (map #(str (:java-type %) " " (:name %)) java-arguments))
        call-arguments (str/join ", " (map :name java-arguments))
        return-prefix (if (= "void" return-type) "" (str "return (" return-type ") "))]
    [(format "    private static final MethodHandle H_%s = FFM.downcall(\"%s\", %s);" name name descriptor)
     (format "    public static %s %s(%s) {" return-type name signature)
     (format "        try { %sH_%s.invokeExact(%s); }" return-prefix name call-arguments)
     "        catch (Throwable t) { throw FFM.failure(t); }"
     "    }"
     ""]))


(let [root (-> *file* fs/absolutize fs/parent fs/parent)
      source (fs/path root "target/automerge/rust/automerge-c/src")
      output (fs/path root "src/co/multiply/rattrapante/internal/Bindings.java")
      _ (when-not (fs/directory? source)
          (throw (ex-info "Automerge source is missing; run bb native first" {:source (str source)})))
      functions (->> (fs/glob source "**.rs")
                  (sort-by str)
                  (mapcat exported-functions)
                  (sort-by :name)
                  vec)
      _ (when (empty? functions)
          (throw (ex-info "No C-ABI functions found; refusing to overwrite bindings" {:source (str source)})))
      header ["// Generated by script/generate_bindings.clj; do not edit."
              "package co.multiply.rattrapante.internal;"
              ""
              "import java.lang.foreign.*;"
              "import java.lang.invoke.MethodHandle;"
              ""
              "public final class Bindings {"]
      lines (conj (into header (mapcat render-function) functions) "}")]
  (spit (fs/file output) (str (str/join "\n" lines) "\n"))
  (println "Generated" (count functions) "exact downcalls in" (str (fs/relativize root output))))
